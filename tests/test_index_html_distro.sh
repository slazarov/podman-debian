#!/bin/bash

# test_index_html_distro.sh -- run generate_index_html (scripts/index_html.sh,
# called by ci_publish.sh Step 5) against a small fixture repo and check the
# page it writes: the distro toggle, one DEB822 snippet per suite, the
# keyring path, the per-distro package tables and HTML escaping.
#
# CI also runs this in the publish job before deploying.
#
# Counters use the assignment form PASS=$((PASS+1)) (not ((PASS++))) so they
# do not return a non-zero status under `set -e` when the counter is 0.

set -euo pipefail

PASS=0
FAIL=0

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Distro table from config.sh, then the generator.
eval "$(sed -n '/^VALID_TRACKS=/,/^unset _distro _track$/p' "${PROJECT_ROOT}/config.sh")"
# shellcheck source=scripts/index_html.sh
source "${PROJECT_ROOT}/scripts/index_html.sh"

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

assert_contains() {
    local file="$1" pattern="$2" label="$3"
    if grep -qF -- "$pattern" "$file"; then
        echo "PASS: $label"
        PASS=$((PASS + 1))
    else
        echo "FAIL: $label: '$pattern' not found in $file" >&2
        FAIL=$((FAIL + 1))
    fi
}

assert_absent() {
    local file="$1" pattern="$2" label="$3"
    if grep -qiF -- "$pattern" "$file"; then
        echo "FAIL: $label: '$pattern' unexpectedly present in $file" >&2
        FAIL=$((FAIL + 1))
    else
        echo "PASS: $label"
        PASS=$((PASS + 1))
    fi
}

assert_count() {
    local file="$1" pattern="$2" want="$3" label="$4"
    local got
    got="$(grep -cF -- "$pattern" "$file" || true)"
    if [[ "${got}" == "${want}" ]]; then
        echo "PASS: $label"
        PASS=$((PASS + 1))
    else
        echo "FAIL: $label: expected ${want} lines with '$pattern', got ${got}" >&2
        FAIL=$((FAIL + 1))
    fi
}

# Fixture: stable on both distros, nightly on trixie only, one hostile version.
mkdir -p "${TMP}/repo/dists/stable-bookworm/main/binary-amd64" \
         "${TMP}/repo/dists/stable-trixie/main/binary-amd64" \
         "${TMP}/repo/dists/nightly-trixie/main/binary-amd64"
cat > "${TMP}/repo/dists/stable-bookworm/main/binary-amd64/Packages" <<'PKG'
Package: podman-podman
Version: 6.0.1~deb12.podman1

Package: podman-crun
Version: 1.25~deb12.podman1
PKG
cat > "${TMP}/repo/dists/stable-trixie/main/binary-amd64/Packages" <<'PKG'
Package: podman-podman
Version: 6.0.1~deb13.podman1
PKG
cat > "${TMP}/repo/dists/nightly-trixie/main/binary-amd64/Packages" <<'PKG'
Package: podman-podman
Version: 6.1.0~~git20261101.<b>x</b>~deb13.podman1
PKG

generate_index_html "${TMP}/repo" "https://example.github.io/podman-debian"
PAGE="${TMP}/repo/index.html"

echo ""
echo "========================================"
echo "Test: index.html generated by generate_index_html"
echo "========================================"
echo ""

# ----- Distro toggle + setDistro() JS -----
assert_contains "$PAGE" "function setDistro"      "setDistro() function defined"
assert_contains "$PAGE" "distro-btn"              ".distro-btn CSS/markup present"
for d in "${VALID_DISTROS[@]}"; do
    assert_contains "$PAGE" "setDistro('${d}')"   "distro button for ${d}"
    assert_count "$PAGE" "data-distro=\"${d}\"" "${#VALID_TRACKS[@]}" "one ${d} snippet per track"
    assert_contains "$PAGE" "Debian ${DISTRO_VERSION_IDS[${d}]} (${d})" "readable name for ${d}"
done

# ----- One DEB822 snippet per suite -----
for suite in "${ALL_SUITES[@]}"; do
    assert_count "$PAGE" "Suites: ${suite}" 1     "snippet for suite ${suite}"
done
assert_count "$PAGE" "Suites: " "${#ALL_SUITES[@]}" "no snippets beyond ALL_SUITES"
for t in "${VALID_TRACKS[@]}"; do
    assert_contains "$PAGE" "id=\"tab-${t}\""     "tab for track ${t}"
done

# ----- Keyring, URL and source file names -----
assert_contains "$PAGE" "Signed-By: /etc/apt/keyrings/podman-debian.gpg" "DEB822 Signed-By keyring path"
assert_contains "$PAGE" "https://example.github.io/podman-debian/podman-debian.gpg" "key URL uses the repo URL"
assert_contains "$PAGE" "URIs: https://example.github.io/podman-debian" "URIs uses the repo URL"
assert_contains "$PAGE" "/etc/apt/sources.list.d/podman-debian.sources" "sources file name"
assert_contains "$PAGE" "https://github.com/slazarov/podman-debian" "source repository link"

# ----- Package tables -----
assert_count "$PAGE" "<th>Package</th>" "${#VALID_DISTROS[@]}" "one package table per distro"
assert_contains "$PAGE" "<code>6.0.1~deb12.podman1</code>" "bookworm stable version listed"
assert_contains "$PAGE" "<code>6.0.1~deb13.podman1</code>" "trixie stable version listed"
assert_contains "$PAGE" "&lt;b&gt;x&lt;/b&gt;"   "versions are HTML-escaped"
assert_absent "$PAGE" "<b>x</b>"                  "no raw markup from Packages data"

# ----- Negative: removed or unsafe content -----
assert_contains "$PAGE" "<title>Podman for Debian" "page title names Debian"
assert_absent "$PAGE" "deprecated"                 "no bare-alias deprecation note"
assert_absent "$PAGE" "/usr/share/keyrings/"       "legacy /usr/share/keyrings/ path absent"
assert_absent "$PAGE" "deb [signed-by="            "legacy deb one-liner snippet absent"
assert_absent "$PAGE" "trusted=yes"                "trusted=yes absent from user-facing snippets"
assert_absent "$PAGE" "Trusted: yes"               "Trusted: yes absent from user-facing snippets"

echo ""
echo "========================================"
echo "Results: ${PASS} passed, ${FAIL} failed"
echo "========================================"

[[ $FAIL -eq 0 ]]
